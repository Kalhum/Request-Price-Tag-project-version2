function encodeCode128B(text: string): number[] {
  const codes: number[] = [104]; // Start B
  let checksum = 104;

  for (let i = 0; i < text.length; i++) {
    const charCode = text.charCodeAt(i);
    const codeVal = charCode >= 32 && charCode <= 126 ? charCode - 32 : 0;
    codes.push(codeVal);
    checksum += codeVal * (i + 1);
  }

  codes.push(checksum % 103);
  codes.push(106); // Stop
  return codes;
}

interface BarcodeSvgProps {
  value: string;
  className?: string;
  height?: number;
}

/**
 * คอมโพเนนต์บาร์โค้ด SVG ที่เรนเดอร์แท่งบาร์โค้ดจริง คมชัด Vector ไม่แตกเวลาสั่งพิมพ์
 */
export default function BarcodeSvg({
  value,
  className = "w-full h-8",
  height = 32,
}: BarcodeSvgProps) {
  const cleanValue = value.trim() || "885099320007";
  const codes = encodeCode128B(cleanValue);

  // แปลงชุด codes เป็นแถบแท่งสีดำและขาว
  const bars: { x: number; width: number }[] = [];
  let currentX = 0;

  for (const code of codes) {
    const pattern = CODE128_PATTERNS[code] || CODE128_PATTERNS[0];
    for (let j = 0; j < pattern.length; j++) {
      const barWidth = pattern[j];
      const isBlack = j % 2 === 0;
      if (isBlack) {
        bars.push({ x: currentX, width: barWidth });
      }
      currentX += barWidth;
    }
  }

  return (
    <svg
      viewBox={`0 0 ${currentX} ${height}`}
      preserveAspectRatio="none"
      className={className}
      fill="#000000"
      xmlns="http://www.w3.org/2000/svg"
      aria-label={`Barcode ${cleanValue}`}
    >
      {bars.map((bar, idx) => (
        <rect
          key={idx}
          x={bar.x}
          y={0}
          width={bar.width}
          height={height}
        />
      ))}
    </svg>
  );
}
